# calc 모듈 add() 함수 정의

def add(a, b) : # a, b 매개변수
    result = a + b
    return result

def multiply(a, b) :
    result = a * b
    return result

def subtract(a, b) :
    result = a - b
    return result

def divide(a, b) :
    result = a / b
    return result

